function slugify(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function reviews(seed) {
  const rating = [4.6, 4.7, 4.8, 4.9, 5][seed % 5];
  const count = 8 + ((seed * 7) % 41);
  return {
    rating,
    count,
    highlights: ['Beautiful finish', 'Feels light to wear', 'Gift-ready packaging'],
  };
}

function features({ material, design, type, length, sku }) {
  const out = [];
  if (material) out.push(material);
  if (design) out.push(`${design} motif`);
  if (type) out.push(type);
  if (length) out.push(`Length: ${length}`);
  out.push('Ships within India in 5–7 working days');
  out.push(`SKU ${sku}`);
  return out;
}

function desc({ name, design, type, material, closing }) {
  const motif = design || 'a quietly considered detail';
  return [
    `${name} brings ${motif.toLowerCase()} into an easy everyday silhouette.`,
    `The design follows a ${type || 'wearable'} form`,
    material ? `, finished in ${material}` : '',
    '.',
    ' Proportions stay expressive without feeling difficult to style.',
    closing ||
      ' A charming piece on its own or beside your everyday favourites — and a thoughtful gift.',
  ].join('');
}

