/** Compact row builder → family objects */
function v(sku, colorLabel, colorSwatch, price, stock, extra = {}) {
  return { sku, colorLabel, colorSwatch, price, stock, ...extra };
}

function family(def) {
  const {
    slug,
    name,
    category,
    collection,
    badge = '',
    material = '925 Sterling Silver',
    design = '',
    type = '',
    length = '',
    variants,
    hasColorVariants,
  } = def;

  const colored = hasColorVariants ?? variants.length > 1;
  return {
    slug,
    name,
    category,
    collection,
    badge,
    hasColorVariants: colored,
    status: 'active',
    active: true,
    variants: variants.map((x, i) => {
      const mat = x.material || material;
      const des = x.design || design;
      const typ = x.type || type;
      const len = x.length || length;
      return {
        slug: colored ? `${slug}-${slugify(x.colorLabel)}` : slug,
        colorLabel: x.colorLabel,
        colorSwatch: x.colorSwatch || SILVER,
        isPrimary: i === 0,
        price: x.price,
        stock: x.stock ?? 0,
        material: mat,
        length: len,
        description:
          x.description ||
          desc({ name, design: des, type: typ, material: mat, closing: x.closing }),
        features: features({
          material: mat,
          design: des,
          type: typ,
          length: len,
          sku: x.sku,
        }),
        reviews: reviews(Number(String(x.sku).replace(/\D/g, '')) || i + 1),
        heroUrl: '',
        gallery: [],
        outOfStock: (x.stock ?? 0) <= 0,
        active: true,
        sku: x.sku,
      };
    }),
  };
}

