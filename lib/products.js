export function getProduct(slug) {
  return products.find((item) => item.slug === slug) ?? null;
}

export function getColorFamily(slug) {
  return (
    colorFamilies.find(
      (family) =>
        family.primary === slug ||
        family.variants.some((variant) => variant.slug === slug) ||
        (family.hide || []).includes(slug),
    ) ?? null
  );
}

export function getProductVariants(slug) {
  const family = getColorFamily(slug);
  if (!family) return [];
  return family.variants
    .map((variant) => {
      const product = getProduct(variant.slug);
      if (!product) return null;
      return { ...variant, product };
    })
    .filter(Boolean);
}

/** Grid listing — one card per color family; hide secondary variants */
export function getListingProducts(list = products) {
  const hidden = new Set();
  for (const family of colorFamilies) {
    for (const variant of family.variants) {
      if (variant.slug !== family.primary) hidden.add(variant.slug);
    }
    for (const slug of family.hide || []) hidden.add(slug);
  }
  return list.filter((item) => !hidden.has(item.slug));
}

export function getRelated(slug, count = 4) {
  const current = getProduct(slug);
  const pool = getListingProducts(products);
  if (!current) return pool.slice(0, count);
  const family = getColorFamily(slug);
  const exclude = new Set([
    slug,
    ...(family?.variants.map((variant) => variant.slug) || []),
    ...(family?.hide || []),
  ]);
  return pool
    .filter((item) => !exclude.has(item.slug))
    .sort((a, b) => {
      const aScore = (a.collection === current.collection ? 2 : 0) + (a.category === current.category ? 1 : 0);
      const bScore = (b.collection === current.collection ? 2 : 0) + (b.category === current.category ? 1 : 0);
      return bScore - aScore;
    })
    .slice(0, count);
}

export function collectionName(slug) {
  return collections.find((item) => item.slug === slug)?.name ?? slug;
}

export function searchProducts(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return getListingProducts(products).filter((item) =>
    [item.name, item.description, item.category, collectionName(item.collection)].join(" ").toLowerCase().includes(q)
  );
}



